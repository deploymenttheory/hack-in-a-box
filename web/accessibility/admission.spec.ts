import { test, expect } from '@playwright/test'
import { activate, scan, tabTo, typeInto } from './checks'
import { admission, admissionActor } from './admission'

test('native registration is keyboard reachable at 390 CSS pixels through real field rejection, review, acceptance and next action', async ({ browser }, info) => {
  const context = await admissionActor(browser, 'applicant'), page = await context.newPage()
  await page.clock.setSystemTime(new Date(admission.instant))
  await page.setViewportSize({ width: 390, height: 844 })
  const writes: { id: string; form_id: string; form_version: number; answers: Record<string, unknown> }[] = []
  page.on('request', request => { if (request.method() === 'POST' && new URL(request.url()).pathname.endsWith('/registrations')) writes.push(request.postDataJSON()) })
  try {
    await page.goto('/register')
    await activate(page, page.getByRole('link', { name: 'Accessibility admission rehearsal', exact: true }))
    const answer = page.getByLabel('Accessibility learning goal (required)', { exact: true })
    await expect(answer).toBeVisible()
    await scan(page, info, 'native-admission-empty-form-390')
    await activate(page, page.getByRole('button', { name: 'Review application', exact: true }))
    const rejected = page.waitForResponse(response => response.request().method() === 'POST' && new URL(response.url()).pathname.endsWith('/registrations') && response.status() === 400)
    await activate(page, page.getByRole('button', { name: 'Submit application', exact: true }))
    await rejected
    await expect(answer).toHaveAttribute('aria-invalid', 'true')
    await expect(answer).toBeFocused()
    await scan(page, info, 'native-admission-server-field-error-390')
    await typeInto(page, answer, 'Synthetic collaboration and keyboard access')
    await tabTo(page, page.getByLabel('Team preference', { exact: true }))
    // Native select type-ahead commits this option. Enter here would submit
    // the surrounding form, so continue by Tab to its explicit review action.
    await page.keyboard.press('i')
    await expect(page.getByLabel('Team preference', { exact: true })).toHaveValue('captain')
    await activate(page, page.getByRole('button', { name: 'Review application', exact: true }))
    await expect(page.getByRole('heading', { name: 'Review your application', exact: true })).toBeVisible()
    await activate(page, page.getByRole('button', { name: 'Correct application details', exact: true }))
    await expect(answer).toHaveValue('Synthetic collaboration and keyboard access')
    await activate(page, page.getByRole('button', { name: 'Review application', exact: true }))
    await scan(page, info, 'native-admission-corrected-review-390')
    const accepted = page.waitForResponse(response => response.request().method() === 'POST' && new URL(response.url()).pathname.endsWith('/registrations') && response.status() === 200)
    await activate(page, page.getByRole('button', { name: 'Submit application', exact: true }))
    const original = await (await accepted).json()
    expect(original.state).toBe('confirmed')
    expect(original.form_id).toBe(admission.form_id)
    expect(original.form_version).toBe(1)
    expect(writes).toHaveLength(2)
    expect(writes[1].id).toBe(writes[0].id)
    expect(original.id).toBe(writes[1].id)
    await expect(page.getByRole('region', { name: 'attendee application status', exact: true }).getByRole('status')).toHaveText('Your competitor place is confirmed.')
    await scan(page, info, 'native-admission-confirmed-result-390')
    await activate(page, page.getByRole('button', { name: 'Create draft team', exact: true }))
    await expect(page.getByLabel('Team name', { exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: 'Review draft team', exact: true })).toBeDisabled()
    const current = await (await context.request.get(`/api/v1/registration/events/${admission.event_id}`)).json()
    expect(current.registrations).toHaveLength(1)
    expect(current.event.stage).toBe('registration')
    expect(current.event.team_frozen).toBe(false)
    expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false)
  } finally { await context.close() }
})

test('native team create, join and captain approval remain keyboard usable while a lost original acknowledgement stays unknown', async ({ browser }, info) => {
  const captainContext = await admissionActor(browser, 'captain'), captain = await captainContext.newPage()
  const teammateContext = await admissionActor(browser, 'teammate'), teammate = await teammateContext.newPage()
  const unknownContext = await admissionActor(browser, 'unknown-joiner'), unknown = await unknownContext.newPage()
  for (const page of [captain, teammate, unknown]) await page.clock.setSystemTime(new Date(admission.instant))
  await teammate.setViewportSize({ width: 390, height: 844 })
  const path = `/api/v1/events/${admission.event_id}/teams`, entry = `/register/${admission.event_id}`
  try {
    await captain.goto(entry)
    await activate(captain, captain.getByRole('button', { name: 'Create draft team', exact: true }))
    const reviewDraft = captain.getByRole('button', { name: 'Review draft team', exact: true })
    await expect(reviewDraft).toBeDisabled()
    await typeInto(captain, captain.getByLabel('Team name', { exact: true }), 'Accessibility keyboard team')
    await activate(captain, reviewDraft)
    await scan(captain, info, 'native-team-create-review')
    await activate(captain, captain.getByRole('button', { name: 'Cancel change', exact: true }))
    await expect(reviewDraft).toBeFocused()
    await expect(captain.getByLabel('Team name', { exact: true })).toHaveValue('Accessibility keyboard team')
    await activate(captain, reviewDraft)
    const created = captain.waitForResponse(response => response.request().method() === 'POST' && new URL(response.url()).pathname === path && response.status() === 200)
    await activate(captain, captain.getByRole('button', { name: 'Confirm team change', exact: true }))
    const original = await (await created).json()
    expect(original.frozen).toBe(false)
    expect(original.can_manage).toBe(false)
    expect(original.teams).toHaveLength(1)
    expect(original.teams[0].draft).toHaveLength(1)
    expect(original.teams[0].published).toHaveLength(0)
    await activate(captain, captain.getByRole('button', { name: 'View Accessibility keyboard team', exact: true }))
    const invitation = await captain.getByLabel('Share this invitation code', { exact: true }).inputValue()
    expect(invitation).toMatch(/^[0-9a-f-]{36}$/)
    await activate(captain, captain.getByRole('button', { name: 'Back to roster', exact: true }))

    await teammate.goto(entry)
    await expect(teammate.getByLabel('Share this invitation code', { exact: true })).toHaveCount(0)
    await expect(teammate.getByRole('button', { name: /^Approve / })).toHaveCount(0)
    await activate(teammate, teammate.getByRole('button', { name: 'Request to join', exact: true }))
    await typeInto(teammate, teammate.getByLabel('Captain’s invitation code', { exact: true }), invitation)
    await activate(teammate, teammate.getByRole('button', { name: 'Review join request', exact: true }))
    await scan(teammate, info, 'native-team-join-review-390')
    const joined = teammate.waitForResponse(response => response.request().method() === 'POST' && new URL(response.url()).pathname === path && response.status() === 200)
    await activate(teammate, teammate.getByRole('button', { name: 'Confirm team change', exact: true }))
    await joined
    await expect(teammate.getByRole('heading', { name: 'Pending join requests', exact: true })).toBeVisible()
    await expect(teammate.getByRole('button', { name: /^Approve / })).toHaveCount(0)
    // A real browser reload rechecks the other actor's committed request; no
    // fixture response or synthetic visibility event substitutes for that read.
    await captain.reload()
    await activate(captain, captain.getByRole('button', { name: 'Approve Synthetic teammate', exact: true }))
    await scan(captain, info, 'native-team-captain-approval-review')
    const approved = captain.waitForResponse(response => response.request().method() === 'POST' && new URL(response.url()).pathname === path && response.status() === 200)
    await activate(captain, captain.getByRole('button', { name: 'Confirm team change', exact: true }))
    const accepted = await (await approved).json()
    expect(accepted.teams[0].draft).toHaveLength(2)
    expect(accepted.teams[0].published).toHaveLength(0)
    expect(accepted.frozen).toBe(false)
    await activate(captain, captain.getByRole('button', { name: 'View Accessibility keyboard team', exact: true }))
    await expect(captain.getByRole('heading', { name: 'Draft membership · 2', exact: true })).toBeVisible()
    await scan(captain, info, 'native-team-accepted-draft-membership')

    let sends = 0
    await unknown.route(`**${path}`, async route => {
      if (route.request().method() !== 'POST') { await route.continue(); return }
      sends++
      const response = await route.fetch()
      expect(response.status()).toBe(200)
      await route.abort('failed')
    })
    await unknown.goto(entry)
    await activate(unknown, unknown.getByRole('button', { name: 'Request to join', exact: true }))
    await typeInto(unknown, unknown.getByLabel('Captain’s invitation code', { exact: true }), invitation)
    await activate(unknown, unknown.getByRole('button', { name: 'Review join request', exact: true }))
    await activate(unknown, unknown.getByRole('button', { name: 'Confirm team change', exact: true }))
    await expect(unknown.getByRole('heading', { name: 'Outcome unknown', exact: true })).toBeVisible()
    await activate(unknown, unknown.getByRole('button', { name: 'Read current roster', exact: true }))
    await expect(unknown.getByText(/Original outcome remains unconfirmed\./)).toBeVisible()
    const current = await (await unknownContext.request.get(path)).json()
    expect(current.frozen).toBe(false)
    expect(current.can_manage).toBe(false)
    expect(current.requests).toHaveLength(1)
    expect(current.requests[0].confirmed).toBe(true)
    expect(current.teams).toHaveLength(0)
    expect(sends).toBe(1)
    await expect(unknown.getByRole('button', { name: 'Confirm team change', exact: true })).toBeDisabled()
    await scan(unknown, info, 'native-team-lost-original-acknowledgement')
    await activate(unknown, unknown.getByRole('button', { name: 'Cancel change', exact: true }))
    await activate(unknown, unknown.getByRole('button', { name: 'Back to roster', exact: true }))
    await expect(unknown.getByRole('complementary', { name: 'Unconfirmed command history', exact: true })).toBeVisible()
    await expect(unknown.getByRole('button', { name: 'Request to join', exact: true })).toBeDisabled()
    expect(sends).toBe(1)
  } finally { await captainContext.close(); await teammateContext.close(); await unknownContext.close() }
})
