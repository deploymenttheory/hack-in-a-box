import { test, expect } from '@playwright/test'

test('production checkpoint fields validate, capture resolved UTC review and restore focus without native requests', async ({ page }) => {
  const calls: string[] = [], errors: string[] = []
  page.on('request', request => { if (/^\/(api|auth)\//.test(new URL(request.url()).pathname)) calls.push(request.url()) })
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/patterns.html')
  const example = page.getByRole('region', { name: 'Mentor checkpoint planning example', exact: true })
  await example.getByRole('button', { name: 'Review checkpoint window', exact: true }).click()
  await expect(example.getByRole('combobox', { name: 'Mentor assessment run', exact: true })).toBeFocused()
  await example.getByRole('combobox', { name: 'Mentor assessment run', exact: true }).selectOption({ index: 1 })
  await expect(example.getByRole('combobox', { name: 'Mentor assessment run', exact: true })).toBeFocused()
  const name = example.getByRole('textbox', { name: 'Checkpoint name', exact: true })
  await name.focus(); await name.pressSequentially('Local provisional observation')
  await expect(name).toBeFocused(); await expect(name).toHaveValue('Local provisional observation')
  await expect(example.getByRole('textbox', { name: 'Checkpoint name', exact: true })).not.toHaveAttribute('aria-invalid', 'true')
  await example.getByLabel('Checkpoint opens', { exact: true }).fill('2027-06-20T10:00')
  await example.getByLabel('Checkpoint closes', { exact: true }).fill('2027-06-20T15:00')
  await example.getByRole('textbox', { name: 'Checkpoint configuration reason', exact: true }).fill('Local reviewed window')
  const opener = example.getByRole('button', { name: 'Review checkpoint window', exact: true })
  await opener.press('Enter')
  const review = page.getByRole('alertdialog', { name: 'Review mentor checkpoint window', exact: true })
  await expect(review).toContainText('Local provisional observation'); await expect(review).toContainText('UTC'); await expect(review).toContainText('Local reviewed window')
  await review.getByRole('button', { name: 'Cancel', exact: true }).click(); await expect(opener).toBeFocused()
  await opener.press('Enter'); await review.getByRole('button', { name: 'Save reviewed checkpoint window', exact: true }).click()
  await expect(example.getByRole('status', { name: 'Local mentor planning result', exact: true })).toContainText('No assessment or checkpoint was sent')
  const before = page.url()
  await example.getByRole('link', { name: 'Review published mentor coverage', exact: true }).click()
  await expect(example.getByRole('status', { name: 'Local mentor planning result', exact: true })).toContainText('Production handoff:')
  expect(page.url()).toBe(before)
  expect(calls).toEqual([]); expect(errors).toEqual([])
})
