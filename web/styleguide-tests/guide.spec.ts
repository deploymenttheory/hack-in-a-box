import { expect, test, type Page, type FrameLocator } from '@playwright/test'

// Run against the actual independent Go host. Any private-store access or API
// connection fails the journey, including access from nested preview documents.
test.beforeEach(async ({ page }) => {
  await page.addInitScript(() => {
    Object.defineProperty(Document.prototype, 'cookie', { configurable: true, get() { throw new Error('Guide read cookies') }, set() { throw new Error('Guide wrote cookies') } })
    for (const method of ['getItem', 'setItem', 'removeItem', 'clear', 'key'] as const) Object.defineProperty(Storage.prototype, method, { value() { throw new Error('Guide accessed private storage') } })
  })
  const errors: string[] = [], requests: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  page.on('request', request => { const url = new URL(request.url()); if (url.protocol.startsWith('http') && (!['/', '/index.html', '/samples.html', '/patterns.html'].includes(url.pathname) && !url.pathname.startsWith('/assets/'))) requests.push(request.url()) })
  await page.goto('/')
  await expect(page.locator('.guide-content > .sr-only')).toHaveCSS('position', 'absolute')
  Object.assign(page, { guideErrors: errors, guideRequests: requests })
})
test.afterEach(async ({ page }) => {
  const evidence = page as Page & { guideErrors: string[]; guideRequests: string[] }
  expect(evidence.guideErrors).toEqual([])
  expect(evidence.guideRequests).toEqual([])
})
async function examples(page: Page, story: 'Components' | 'Task patterns') {
  await page.getByRole('link', { name: story, exact: true }).click()
  const title = story === 'Components' ? 'Production component examples' : 'Production task pattern examples'
  return page.frameLocator(`iframe[title="${title}"]`)
}
async function scenario(frame: FrameLocator, mode: string) {
  const details = frame.locator('details.fleet-example-settings')
  if (!await details.evaluate(element => element.hasAttribute('open'))) await frame.getByText('Synthetic scenario controls', { exact: true }).click()
  await frame.getByLabel('Synthetic transport', { exact: true }).selectOption(mode)
}
