import { test, expect } from '@playwright/test'
test('production Today guide keeps context, owner focus, observation and print boundaries explicit', async ({ page }) => {
 const calls: string[] = []; page.on('request', request => { if (new URL(request.url()).pathname.startsWith('/api/')) calls.push(request.url()) })
 await page.goto('/')
 const guide = page.getByRole('region', { name: 'Role-specific Today example', exact: true })
 await guide.getByRole('combobox', { name: 'Today context' }).selectOption('judge')
 await expect(guide.getByRole('heading', { name: 'Synthetic judge preparation' })).toBeVisible()
 await guide.getByRole('button', { name: 'Open synthetic preparation owner' }).click()
 await expect(guide.getByRole('heading', { name: 'Synthetic preparation owner', exact: true })).toBeFocused()
 await guide.getByRole('button', { name: 'Read synthetic updated preparation' }).click()
 await guide.getByRole('button', { name: 'Back to synthetic Today' }).click()
 await expect(guide.getByRole('button', { name: 'Open synthetic preparation owner' })).toBeFocused()
 await guide.getByRole('button', { name: 'Change synthetic server observation' }).click()
 await expect(guide.getByText('Common release not recorded', { exact: true })).toBeVisible()
 await expect(guide.getByText('Cutoff reached at the server observation', { exact: true })).toBeVisible()
 await guide.getByRole('combobox', { name: 'Synthetic Today read' }).selectOption('paused')
 await expect(guide.getByRole('button', { name: 'Open synthetic preparation owner' })).toBeDisabled()
 await guide.getByRole('combobox', { name: 'Synthetic Today read' }).selectOption('denied')
 await expect(guide.getByRole('heading', { name: 'Synthetic judge preparation' })).toHaveCount(0)
 await guide.getByRole('combobox', { name: 'Synthetic Today read' }).selectOption('ready')
 await page.emulateMedia({ media: 'print' })
 await expect(guide.getByRole('region', { name: 'Your event Today' })).not.toBeVisible()
 expect(calls).toEqual([])
})
