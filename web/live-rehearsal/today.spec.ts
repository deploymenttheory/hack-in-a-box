import { test, expect } from '@playwright/test'
import { openEventSection } from '../e2e/event-navigation-fixture'
import { actor, control, native } from './native'

test('actual Today rules, contacts and personal completion remain separate from native team submission readiness', async ({ browser }, info) => {
  await control('clock', { instant: '2027-03-29T09:00:00Z' })
  await control('reset-room')
  const context = await actor(browser, 'public', 'competitor'), page = await context.newPage()
  await page.setViewportSize({ width: 390, height: 844 })
  const formalWrites: string[] = []
  page.on('request', request => { if (request.method() === 'POST' && new URL(request.url()).pathname.endsWith('/submission')) formalWrites.push(request.url()) })
  const submissionPath = `/api/v1/events/${native.event_id}/teams/${native.team_id}/submission`
  try {
    const before = await (await context.request.get(submissionPath)).json()
    await page.goto(`/events/${native.event_id}`)
    await openEventSection(page, 'Today')
    const today = page.getByRole('region', { name: 'Your event Today', exact: true })
    await expect(today.getByRole('region', { name: 'Published room program', exact: true })).toContainText('Rehearsal opening')
    const readiness = page.getByRole('region', { name: 'Separate personal and team readiness', exact: true })
    await expect(readiness).toContainText('0 complete · 0 waived · 1 current tasks')
    await expect(readiness).toContainText('Rehearsal team')
    const guidance = page.getByRole('region', { name: 'Rules and contacts', exact: true })
    await expect(guidance.getByRole('link', { name: 'Synthetic support desk', exact: true })).toHaveAttribute('href', 'https://support.example.test/rehearsal')
    const rulesOpener = guidance.getByRole('button', { name: 'Read Rehearsal rules', exact: true })
    await rulesOpener.focus()
    await page.keyboard.press('Enter')
    await expect(page.getByRole('heading', { name: 'Rehearsal rules', exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'I have read version 1', exact: true }).click()
    const acknowledgement = page.waitForResponse(response => response.request().method() === 'POST' && new URL(response.url()).pathname.endsWith('/acknowledgements') && response.status() === 200)
    await page.getByRole('button', { name: 'Confirm acknowledgement', exact: true }).click()
    const receipt = await (await acknowledgement).json()
    expect(receipt.version).toBe(1)
    expect(receipt.acknowledged_at).toBeTruthy()
    await page.getByRole('button', { name: 'Back to resources', exact: true }).click()
    await expect(rulesOpener).toBeFocused()
    await page.getByRole('button', { name: 'Refresh Today facts', exact: true }).click()
    await expect(page.getByRole('region', { name: 'Rules and contacts', exact: true })).toContainText('You acknowledged version 1')
    await page.getByRole('button', { name: 'Open your preparation workspace', exact: true }).click()
    await page.getByRole('button', { name: 'Open Rehearsal personal setup', exact: true }).click()
    await page.getByLabel('Preparation status', { exact: true }).selectOption('complete')
    await page.getByRole('checkbox', { name: 'Verify local setup', exact: true }).check()
    await page.getByLabel('Progress reason', { exact: true }).fill('Completed synthetic personal setup; team evidence remains separate.')
    await page.getByRole('button', { name: 'Save preparation progress', exact: true }).click()
    const saved = page.waitForResponse(response => response.request().method() === 'PUT' && new URL(response.url()).pathname.includes('/preparation/tasks/') && response.status() === 200)
    await page.getByRole('button', { name: 'Confirm preparation progress', exact: true }).click()
    await saved
    await expect(page.getByRole('region', { name: 'Personal preparation task', exact: true }).getByRole('status')).toContainText('Preparation progress saved.')
    await openEventSection(page, 'Today')
    await expect(page.getByRole('region', { name: 'Separate personal and team readiness', exact: true })).toContainText('1 complete · 0 waived · 1 current tasks')
    const after = await (await context.request.get(submissionPath)).json()
    expect(after.revision).toBe(before.revision)
    expect(after.outcome).toBe(before.outcome)
    expect(after.final).toEqual(before.final)
    expect(formalWrites).toEqual([])
    expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false)
    await page.screenshot({ path: info.outputPath('native-today-personal-and-team-readiness.png'), fullPage: true })
  } finally { await context.close() }
})

test('administrator Today observes the native published program and leads current MC authority into its console', async ({ browser }, info) => {
  await control('clock', { instant: '2027-03-29T09:00:00Z' })
  await control('reset-room')
  const context = await actor(browser, 'admin', 'mc'), page = await context.newPage()
  try {
    const response = await context.request.get(`/api/v1/events/${native.event_id}/today`)
    expect(response.status()).toBe(200)
    expect(response.headers()['cache-control']).toContain('no-store')
    const current = await response.json()
    expect(current.roles).toEqual(['mc'])
    expect(current.program.current.title).toBe('Rehearsal opening')
    expect(current.program.next.title).toBe('Rehearsal building')
    expect(JSON.stringify(current)).not.toContain('PRIVATE-')
    expect(current.program.draft).toBeUndefined()
    expect(current.program.pairings).toBeUndefined()
    await page.goto(`/events/${native.event_id}`)
    await openEventSection(page, 'Today')
    await page.getByLabel('Today context', { exact: true }).selectOption('mc')
    await expect(page.getByRole('region', { name: 'Published room program', exact: true })).toContainText(current.program.current.title)
    await page.getByRole('button', { name: 'Open MC console', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'MC console', exact: true })).toBeVisible()
    await expect(page.getByRole('region', { name: 'Live room controls', exact: true })).toContainText(current.program.current.title)
    await page.screenshot({ path: info.outputPath('native-today-to-authorized-mc-console.png'), fullPage: true })
  } finally { await context.close() }
})
