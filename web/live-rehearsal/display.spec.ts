import { test, expect } from '@playwright/test'
import { openEventSection } from '../e2e/event-navigation-fixture'
import { actor, control, native } from './native'

test('native MC pairs an independent display; outage converges without duplicate room actions', async ({ browser }, info) => {
  const mcContext = await actor(browser, 'admin', 'mc')
  const displayContext = await browser.newContext({ baseURL: native.display })
  const mc = await mcContext.newPage(), display = await displayContext.newPage()
  try {
    await control('reset-room')
    await mc.goto(`/events/${native.event_id}`)
    await openEventSection(mc, 'MC console')
    await mc.getByLabel('Reason for room changes').fill('Reviewed synthetic integrated room rehearsal')
    await mc.getByRole('button', { name: 'Manage displays', exact: true }).click()
    const label = `Rehearsal ${info.project.name}`
    await mc.getByLabel('Display label', { exact: true }).fill(label)
    await mc.getByRole('button', { name: 'Pair display', exact: true }).click()
    await mc.getByRole('button', { name: 'Confirm display pairing', exact: true }).click()
    const token = await mc.getByRole('textbox', { name: 'New display secret', exact: true }).inputValue()
    expect(token.length).toBeGreaterThan(30)
    await mc.getByRole('button', { name: 'Dismiss display secret', exact: true }).click()
    const displayRequests: { path: string; authorization: boolean; cookie: boolean }[] = []
    display.on('request', request => {
      const url = new URL(request.url())
      if (url.pathname.startsWith('/api/')) displayRequests.push({ path: url.pathname, authorization: !!request.headers().authorization, cookie: !!request.headers().cookie })
      expect(url.search).not.toContain(token)
    })
    await display.goto(`/display/${native.event_id}`)
    await display.getByLabel('Display key', { exact: true }).fill(token)
    await display.getByRole('button', { name: 'Connect display', exact: true }).click()
    await expect(display.getByRole('heading', { name: 'Rehearsal opening', exact: true })).toBeVisible()
    await expect(display.getByLabel(/^Countdown \d{2}:\d{2}$/)).toBeVisible()
    await display.screenshot({ path: info.outputPath('native-connected-opening.png') })
    const before = await control<{ event_revision: number; presentation_revision: number; provider_jobs: number }>('evidence')
    await control('outage')
    await expect(display.getByRole('status').filter({ hasText: 'Connection lost' })).toBeVisible()
    await expect(display.getByRole('heading', { name: 'Rehearsal opening', exact: true })).toBeVisible()
    await display.screenshot({ path: info.outputPath('native-disconnected-last-authorized-opening.png') })
    await mc.screenshot({ path: info.outputPath('native-mc-approved-controls.png'), fullPage: true })
    await mc.getByRole('button', { name: 'Live controls', exact: true }).click()
    await mc.getByRole('button', { name: 'Advance', exact: true }).click()
    await mc.getByRole('button', { name: 'Confirm room change', exact: true }).click()
    await expect(mc.getByRole('region', { name: 'Live room controls' })).toContainText('Rehearsal building')
    await control('restore')
    await expect(display.getByRole('heading', { name: 'Rehearsal building', exact: true })).toBeVisible()
    const after = await control<{ event_revision: number; presentation_revision: number; provider_jobs: number }>('evidence')
    expect(after.event_revision).toBe(before.event_revision)
    expect(after.presentation_revision).toBe(before.presentation_revision + 1)
    expect(after.provider_jobs).toBe(0)
    expect(displayRequests.length).toBeGreaterThan(1)
    expect(displayRequests.every(request => /^\/api\/v1\/events\/[^/]+\/display\/(stream|snapshot|assets\/[^/]+)$/.test(request.path) && request.authorization && !request.cookie)).toBe(true)
    expect(await display.evaluate(() => JSON.stringify({ local: { ...localStorage }, session: { ...sessionStorage } }))).not.toContain(token)
    const snapshotResponse = await displayContext.request.get(`/api/v1/events/${native.event_id}/display/snapshot`, { headers: { Authorization: `Bearer ${token}` } })
    expect(snapshotResponse.status()).toBe(200)
    expect(snapshotResponse.headers()['cache-control']).toContain('no-store')
    const snapshot = await snapshotResponse.json()
    expect(Object.keys(snapshot).sort()).toEqual(['assets', 'results', 'override_active', 'event_id', 'event_name', 'timezone', 'sequence', 'server_now', 'current', 'next', 'mode', 'remaining_seconds', 'timer_ends_at', 'primary_colour', 'background_colour', 'foreground_colour'].sort())
    expect(snapshot.results).toEqual([]) // No deliberate finalist or award release occurred.
    expect(JSON.stringify(snapshot)).not.toContain('PRIVATE-')
    expect(snapshot.sequence).toBe(after.presentation_revision)
    const privateController = await displayContext.request.get(`/api/v1/events/${native.event_id}/presentation`, { headers: { Authorization: `Bearer ${token}` } })
    expect(privateController.status()).toBe(401)
    expect(await display.evaluate(async () => {
      const names = await caches.keys()
      const bodies: string[] = []
      for (const name of names) for (const request of await (await caches.open(name)).keys()) bodies.push(await (await (await caches.open(name)).match(request))!.text())
      return JSON.stringify({ bodies, local: { ...localStorage }, session: { ...sessionStorage } })
    })).not.toContain('PRIVATE-')
    await display.screenshot({ path: info.outputPath('native-reconnected-display.png') })
    // Real browser offline is independent from a backend outage. A later native
    // server clock replaces the client's deliberately incorrect wall clock.
    await display.clock.setSystemTime(new Date('2040-01-01T00:00:00Z'))
    await displayContext.setOffline(true)
    await expect(display.getByRole('status').filter({ hasText: 'Connection lost' })).toBeVisible()
    await expect(display.getByRole('heading', { name: 'Rehearsal building', exact: true })).toBeVisible()
    const serverNow = new Date(snapshot.server_now)
    await control('clock', { instant: new Date(serverNow.getTime() + 30_000).toISOString() })
    await displayContext.setOffline(false)
    await expect(display.getByRole('status')).toContainText('Live room feed')
    await expect(display.getByLabel('Countdown 00:30', { exact: true })).toBeVisible()
    const afterOffline = await control<{ presentation_revision: number }>('evidence')
    expect(afterOffline.presentation_revision).toBe(after.presentation_revision)
    await mc.getByRole('button', { name: 'Hold countdown', exact: true }).click()
    await mc.getByRole('button', { name: 'Confirm room change', exact: true }).click()
    await expect(display.getByText('Timer held', { exact: true })).toBeVisible()
    await control('clock', { instant: new Date(serverNow.getTime() + 90_000).toISOString() })
    await expect(display.getByLabel('Countdown 00:30', { exact: true })).toBeVisible()
    await expect(display.getByRole('heading', { name: 'Rehearsal building', exact: true })).toBeVisible()
    await mc.getByRole('button', { name: 'Manage displays', exact: true }).click()
    await mc.getByRole('button', { name: `Revoke ${label}`, exact: true }).click()
    await mc.getByRole('button', { name: 'Confirm display revocation', exact: true }).click()
    await expect(display.getByRole('heading', { name: 'Connect a room display', exact: true })).toBeVisible()
    await expect(display.getByRole('heading', { name: 'Rehearsal building', exact: true })).toHaveCount(0)
  } finally {
    await control('restore')
    await mcContext.close()
    await displayContext.close()
  }
})
